"""Operational metrics library (Task 18): deterministic numbers about a business's AI team.

Every number the dashboard, the Excel export or the Data Analyst shows comes from here: sums
of `daily_metrics` (UTC days, computed by the worker from conversations and the audit trail,
see migration 0020) and ratios derived from those sums in code. Nothing is estimated or
generated by a model. Days the job has not computed yet are reported as missing, never as zero.
"""

import asyncio
import logging
import re
from collections.abc import Sequence
from dataclasses import dataclass, field
from datetime import UTC, date, datetime, timedelta

from sqlalchemy import select, text
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

from agentree.analytics.models import DailyMetric, MetricDay
from agentree.tenancy.context import TenantContext
from agentree.tenancy.db import tenant_session

logger = logging.getLogger(__name__)
Factory = async_sessionmaker[AsyncSession]

# name -> label. Order is the display order.
METRICS: dict[str, str] = {
    "conversations": "Visitor conversations",
    "visitor_messages": "Visitor messages",
    "ai_replies": "AI replies",
    "away_replies": "Away messages (agent not available)",  # Task 20b: fixed, not AI
    "team_replies": "Team replies",
    "agent_handoffs": "Handoffs between AI agents",
    "handoffs_to_team": "Handoffs to your team",
    "resolved": "Conversations resolved",
    "leads": "New leads",
    "customers_verified": "Customers who confirmed their email",
}
# Per-agent outcomes (Task 21), stored as "agent:<role>:<outcome>".
AGENT_OUTCOMES: dict[str, str] = {
    "conversations": "Conversations answered",
    "replies": "AI replies",
    "resolved": "Resolved while leading",
    "to_team": "Handed to your team",
    "handoffs_out": "Handed to another agent",
}
_AGENT_METRIC = re.compile(r"^agent:([a-z_]{1,32}):([a-z_]{1,16})$")
BACKFILL_DAYS = 30  # raw messages exist this long; older days cannot be recomputed
MAX_RANGE_DAYS = 400


class InvalidRangeError(ValueError):
    pass


@dataclass(frozen=True)
class DayRow:
    day: date
    values: dict[str, int]


@dataclass(frozen=True)
class Summary:
    start: date
    end: date  # inclusive
    totals: dict[str, int]
    rates: dict[str, float | None]  # percentages, one decimal; None when undefined
    days: list[DayRow]
    missing_days: list[date] = field(default_factory=list)  # not computed: unknown, not zero
    agents: dict[str, dict[str, int]] = field(default_factory=dict)  # role -> outcome -> total


def utc_today() -> date:
    return datetime.now(UTC).date()


def month_range(month: str) -> tuple[date, date]:
    """'2026-10' -> (2026-10-01, 2026-10-31); refuses malformed or future months."""
    try:
        year, mon = (int(x) for x in month.split("-"))
        start = date(year, mon, 1)
    except ValueError:
        raise InvalidRangeError("month") from None
    nxt = date(year + (mon == 12), 1 if mon == 12 else mon + 1, 1)
    if start > utc_today():
        raise InvalidRangeError("month")
    return start, nxt - timedelta(days=1)


def _pct(part: int, whole: int) -> float | None:
    return round(100 * part / whole, 1) if whole else None


def rates(totals: dict[str, int]) -> dict[str, float | None]:
    conv = totals.get("conversations", 0)
    return {
        "lead_rate": _pct(totals.get("leads", 0), conv),
        "handoff_to_team_rate": _pct(totals.get("handoffs_to_team", 0), conv),
        "resolution_rate": _pct(totals.get("resolved", 0), conv),
    }


RATE_LABELS = {
    "lead_rate": "Conversations that became a lead (%)",
    "handoff_to_team_rate": "Conversations handed to your team (%)",
    "resolution_rate": "Conversations resolved (%)",
}


async def summary(factory: Factory, ctx: TenantContext, start: date, end: date) -> Summary:
    """Totals, rates and per-day values for start..end (inclusive, UTC days)."""
    if end < start or (end - start).days >= MAX_RANGE_DAYS:
        raise InvalidRangeError("range")
    end = min(end, utc_today())
    async with tenant_session(factory, ctx) as session:
        rows = (
            await session.execute(
                select(DailyMetric.day, DailyMetric.metric, DailyMetric.value)
                .where(DailyMetric.business_id == ctx.business_id,
                       DailyMetric.day >= start, DailyMetric.day <= end)
            )
        ).all()  # fmt: skip
        computed = set(
            (
                await session.execute(
                    select(MetricDay.day).where(MetricDay.day >= start, MetricDay.day <= end)
                )
            ).scalars()
        )
    by_day: dict[date, dict[str, int]] = {}
    agents: dict[str, dict[str, int]] = {}
    for day, metric, value in rows:
        if metric in METRICS:
            by_day.setdefault(day, {})[metric] = value
        elif (found := _AGENT_METRIC.match(metric)) and day in computed:
            role, outcome = found.groups()
            if outcome in AGENT_OUTCOMES:
                agents.setdefault(role, dict.fromkeys(AGENT_OUTCOMES, 0))[outcome] += value
    days, missing = [], []
    totals = dict.fromkeys(METRICS, 0)
    d = start
    while d <= end:
        if d in computed:
            values = {m: by_day.get(d, {}).get(m, 0) for m in METRICS}
            days.append(DayRow(d, values))
            for m, v in values.items():
                totals[m] += v
        else:
            missing.append(d)
        d += timedelta(days=1)
    return Summary(start, end, totals, rates(totals), days, missing, agents)


def as_text(s: Summary, title: str) -> str:
    """A plain block of the numbers (for the Data Analyst's prompt)."""
    lines = [f"{title}: {s.start.isoformat()} to {s.end.isoformat()} (UTC days)"]
    lines += [f"- {METRICS[m]}: {v}" for m, v in s.totals.items()]
    lines += [f"- {RATE_LABELS[r]}: {'n/a' if v is None else v}" for r, v in s.rates.items()]
    if s.missing_days:
        lines.append(f"- Days not computed yet (unknown, not zero): {len(s.missing_days)}")
    return "\n".join(lines)


# --- worker ----------------------------------------------------------------------------------


async def compute_due(factory: Factory, *, today: date | None = None) -> int:
    """Compute today and yesterday (they change), plus any missing day of the last 30."""
    today = today or utc_today()
    async with factory() as session:
        done = set((await session.execute(
            select(MetricDay.day).where(MetricDay.day >= today - timedelta(days=BACKFILL_DAYS))
        )).scalars())  # fmt: skip
    due = [today, today - timedelta(days=1)]
    due += [today - timedelta(days=i) for i in range(2, BACKFILL_DAYS + 1)
            if today - timedelta(days=i) not in done]  # fmt: skip
    rows = 0
    for day in due:
        async with factory() as session, session.begin():
            rows += int((await session.execute(
                text("SELECT agentree_compute_daily_metrics(:d)"), {"d": day}
            )).scalar_one())  # fmt: skip
    return rows


async def run_metrics_loop(factory: Factory, *, interval_seconds: float,
                           stop: asyncio.Event) -> None:  # fmt: skip
    while not stop.is_set():
        try:
            await compute_due(factory)
        except Exception as exc:  # keep the worker alive; the next pass retries
            logger.error("daily metrics failed", extra={"error_type": type(exc).__name__})
        try:
            await asyncio.wait_for(stop.wait(), timeout=interval_seconds)
        except TimeoutError:
            pass


def last_full_months(today: date, n: int) -> Sequence[str]:
    """'YYYY-MM' of the current month and the n-1 before it."""
    out, y, m = [], today.year, today.month
    for _ in range(n):
        out.append(f"{y:04d}-{m:02d}")
        y, m = (y - 1, 12) if m == 1 else (y, m - 1)
    return out


async def analyst_numbers(factory: Factory, ctx: TenantContext) -> str:
    """The computed numbers the Data Analyst may state: last 7 and 30 days, this month and
    last month (complete UTC days through today)."""
    today = utc_today()
    this_month = today.replace(day=1)
    prev_end = this_month - timedelta(days=1)
    periods = [
        ("Last 7 days", today - timedelta(days=6), today),
        ("Last 30 days", today - timedelta(days=29), today),
        ("This month so far", this_month, today),
        ("Last month", prev_end.replace(day=1), prev_end),
    ]
    blocks = [as_text(await summary(factory, ctx, s, e), title) for title, s, e in periods]
    return "\n\n".join(blocks)
