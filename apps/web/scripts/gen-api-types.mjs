// Regenerates src/lib/api-types.ts from the FastAPI OpenAPI schema.
//
// Default: renders the schema offline from apps/api (needs `uv`; no database connection is
// made, the URL below is a placeholder that is never dialled).
// Override: AGENTREE_OPENAPI_SOURCE=<url or file path>, e.g. http://127.0.0.1:8000/openapi.json
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(here, "..");
const apiRoot = resolve(webRoot, "../api");
const outFile = resolve(webRoot, "src/lib/api-types.ts");

async function loadSchema() {
  const source = process.env.AGENTREE_OPENAPI_SOURCE;
  if (source && /^https?:\/\//.test(source)) {
    const res = await fetch(source);
    if (!res.ok) throw new Error(`GET ${source} -> ${res.status}`);
    return await res.json();
  }
  if (source) return JSON.parse(readFileSync(resolve(source), "utf8"));
  const stdout = execFileSync(
    "uv",
    [
      "run",
      "--frozen",
      "python",
      "-c",
      "import json; from agentree.main import create_app; print(json.dumps(create_app().openapi()))",
    ],
    {
      cwd: apiRoot,
      encoding: "utf8",
      env: {
        ...process.env,
        AGENTREE_ENVIRONMENT: "dev",
        AGENTREE_DATABASE_URL: "postgresql+asyncpg://placeholder:placeholder@127.0.0.1:1/placeholder",
      },
    },
  );
  return JSON.parse(stdout);
}

const schema = await loadSchema();
const ast = await openapiTS(schema);
const banner =
  "// Generated by `npm run gen:api` from the FastAPI OpenAPI schema. Do not edit by hand.\n\n";
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, banner + astToString(ast));
console.log(`wrote ${outFile}`);
